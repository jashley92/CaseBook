# WebAdministration cmdlets throw 0x8007000D ("data is invalid") when targeting a site. appcmd with
# /commit:apphost writes a <location> entry into applicationHost.config, which the lock permits. Requires
# the Web-Windows-Auth role feature (Install-WindowsFeature Web-Windows-Auth -IncludeManagementTools).
$appcmd = Join-Path $env:WINDIR 'System32\inetsrv\appcmd.exe'
if (-not (Test-Path $appcmd)) { throw "appcmd.exe not found at $appcmd - is the IIS 'Web-Server' role installed?" }

