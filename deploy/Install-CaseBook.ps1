#Requires -Version 5.1
#Requires -RunAsAdministrator
<#
.SYNOPSIS
    First-install of the CaseBook web app on a Windows Server 2022 IIS host.

.DESCRIPTION
    End-to-end app install (run AFTER Install-Database.ps1):
      1. Publishes the Blazor Server app (dotnet publish -c Release) to the site folder.
      2. Creates the ACL-restricted data root (evidence / reports / keys / seals / ops)
         OUTSIDE the web root.
      3. Writes appsettings.Production.json from the template with your values.
      4. Creates/updates the IIS application pool (No Managed Code, your service identity)
         and website, enabling Windows Authentication and disabling Anonymous (except under /api,
         /health, /branding/logo and /agenda/feed.ics, which the app authenticates or keeps status-only).
      5. Grants the app-pool identity least-privilege NTFS rights.

    Integrated auth throughout - no secrets are written by this script. Provide the app-pool
    identity as a gMSA (recommended, passwordless) or a domain service account.
    Re-runnable to repair an install: it stops the app pool before publishing over the site, and keeps an
    existing appsettings.Production.json (it may hold later changes: CyberArk, retired chain keys, seal copies,
    alert lists), writing the newly generated one beside it as appsettings.Production.json.new to compare.
    Pass -ReplaceSettings to overwrite it. To UPDATE an installed app, use Upgrade-CaseBook.ps1.

    Values can come from an answers file (-ConfigFile casebook.config.psd1, generated by
    New-CaseBookConfig.ps1 - the same file Install-Database.ps1 uses) OR as parameters. A
    parameter you pass explicitly overrides the file. A non-gMSA password is NEVER read from
    the file - pass -AppPoolCredential, or the script prompts for it securely before changing anything.

.PARAMETER ConfigFile
    Path to a casebook.config.psd1 answers file (see casebook.config.template.psd1). Fills any
    parameter you don't pass explicitly. Optional - you can pass everything as parameters.

.PARAMETER AppPoolIdentity
    Service account the app runs as, matching the SQL login from Install-Database.ps1.
    (Config-file key / alias: AppAccount.) gMSA: "CONTOSO\svc-casebook$" (leave -AppPoolCredential unset).

.PARAMETER AppPoolCredential
    Only for a NON-gMSA domain service account: a PSCredential (you are prompted securely).
    Omit for a gMSA.

.PARAMETER SitePath
    Web root the app is published to, e.g. "D:\inetpub\casebook". Kept separate from DataRoot.

.PARAMETER DataRoot
    Root for evidence/reports/keys/seals/ops, OUTSIDE the web root, e.g. "E:\CaseBookData".

.PARAMETER EvidencePath
    PROD-56: where evidence is stored, if not <DataRoot>\evidence-store. A local folder or a UNC share path, e.g.
    "\\files01\casebook$\evidence". On a share, the app-pool account needs Modify on the folder and Change on the
    share; the script sets the folder's rights when it can and says exactly what to grant when it can't. With the
    built-in ApplicationPoolIdentity the share sees this server's computer account (DOMAIN\HOST$); a gMSA is clearer.

.PARAMETER Hostname
    Public host header, e.g. "casebook.contoso.com".

.PARAMETER SqlInstance / DbName
    SQL Server instance and database from Install-Database.ps1.

.PARAMETER CertificateThumbprint
    Thumbprint of an installed TLS cert for an HTTPS (443) binding. If omitted, an HTTP
    binding is created and you are warned to terminate TLS in front.

.PARAMETER AdGroupAnalysts / Commanders / Leadership / Legal / AppAdmins
    Real AD security-group names mapped to the five application roles, as DOMAIN\Group (a bare name is
    qualified with the domain it resolves to here; BUG-224).

.PARAMETER SmtpHost / MailDomain
    Optional email settings (email stays disabled until enabled in-app).

.PARAMETER SmtpSignIn
    CAP-05: how CaseBook signs in to the relay. 'App' (default): set it after install in Administration -> Settings ->
    Notifications -> Email sign-in, where the password is encrypted with Data Protection. 'Windows': sign in as the
    app-pool account (on-premises Exchange; no password). 'Password': -SmtpUsername with a password written into
    appsettings.Production.json (which then wins over the form), as -SmtpPasswordSource says.

.PARAMETER SmtpPasswordSource
    With -SmtpSignIn Password: 'Protected' (default; the password is prompted for, or taken from -SmtpPassword, and only
    its @protected: value from deploy\keytool\casebook-keytool protect-secret is written, encrypted to
    -SmtpPasswordThumbprint or the integrity certificate), 'CyberArk' (-SmtpPasswordSecret = an @cyberark: reference) or
    'Literal' (plain text in the file; not recommended). The password is never read from the answers file.

.PARAMETER SkipPublish
    Do not run 'dotnet publish' on this host. Use when the server has no nuget.org access
    (NU1100 restore errors) or no SDK: publish on a machine WITH internet, copy the output
    into -SitePath, then run with -SkipPublish to do only IIS + config + ACLs.

.PARAMETER AddNuGetOrgSource
    If no NuGet source is registered (publish would fail NU1100), register nuget.org
    automatically rather than stopping with instructions. Off by default so an intentional
    internal-feed-only policy isn't overridden.

.EXAMPLE
    # Simplest: one answers file for both installers (a gMSA needs no credential).
    .\Install-CaseBook.ps1 -ConfigFile .\casebook.config.psd1
    # Normal (non-gMSA) service account - add the credential prompt:
    .\Install-CaseBook.ps1 -ConfigFile .\casebook.config.psd1 -AppPoolCredential (Get-Credential)

.EXAMPLE
    .\Install-CaseBook.ps1 -AppPoolIdentity "CONTOSO\svc-casebook$" `
        -SitePath D:\inetpub\casebook -DataRoot E:\CaseBookData `
        -Hostname casebook.contoso.com -SqlInstance SQLHOST\PROD -DbName CaseBook `
        -CertificateThumbprint AABBCC... `
        -AdGroupAnalysts CONTOSO\SOC-Analysts -AdGroupCommanders CONTOSO\SOC-IncidentCommanders `
        -AdGroupLeadership CONTOSO\SOC-Leadership -AdGroupLegal CONTOSO\Legal-Privacy -AdGroupAppAdmins CONTOSO\SOC-AppAdmins
#>
[CmdletBinding()]
param(
    [string] $ConfigFile,

    [Alias('AppAccount')]
    [string] $AppPoolIdentity,
    [System.Management.Automation.PSCredential] $AppPoolCredential,

    [string] $SitePath,
    [string] $DataRoot,
    [string] $EvidencePath = '',
    [string] $Hostname,
    [string] $SqlInstance,
    [string] $DbName = 'CaseBook',

    [string] $SiteName = 'CaseBook',
    [string] $AppPoolName = 'CaseBook',
    [string] $CertificateThumbprint,

    [string] $AdGroupAnalysts,
    [string] $AdGroupCommanders,
    [string] $AdGroupLeadership,
    [string] $AdGroupLegal,
    [string] $AdGroupAppAdmins,

    [string] $SmtpHost = '',
    [string] $MailDomain = '',
    # CAP-05: the relay sign-in. The password itself is only ever prompted for, or passed as a SecureString.
    [ValidateSet('App', 'Windows', 'Password')]
    [string] $SmtpSignIn = 'App',
    [string] $SmtpUsername = '',
    [ValidateSet('Protected', 'CyberArk', 'Literal')]
    [string] $SmtpPasswordSource = 'Protected',
    [string] $SmtpPasswordSecret = '',
    [string] $SmtpPasswordThumbprint = '',
    [System.Security.SecureString] $SmtpPassword,

    # Integrity keys (ADR 0016; OPERATIONS.md section 2).
    [ValidateSet('File', 'CertificateStore', 'CyberArk')]
    [string] $SigningKeySource = 'File',
    [string] $SigningKeyThumbprint = '',
    [string] $SigningKeySecret = '',
    # '' keeps the audit chain key off (the default).
    [ValidateSet('', 'CyberArk', 'Certificate')]
    [string] $ChainKeySource = '',
    [string] $ChainKeySecret = '',
    [string] $ChainKeyThumbprint = '',

    # Evidence encryption at rest (PROD-57; OPERATIONS.md section 2, Evidence key). Off unless set.
    [bool] $EvidenceEncryption = $false,
    [string] $EvidenceKeyThumbprint = '',
    # Recovery certificates: paths to .cer files (public part only). Copied to <DataRoot>\keys\recovery.
    [string[]] $RecoveryCertificates = @(),

    [string] $PublishConfiguration = 'Release',

    # Air-gapped / no nuget.org on this host: publish on a machine WITH internet
    # (dotnet publish src/IncidentManager.Web -c Release -o <folder>), copy the output
    # into -SitePath, then re-run with -SkipPublish to do only IIS + config + ACLs.
    [switch] $SkipPublish,

    # If NO NuGet package source is registered (publish would fail NU1100), register nuget.org
    # automatically instead of stopping. Off by default: a blank source list can be deliberate
    # policy (use an internal feed), and this writes to the running user's NuGet.Config.
    [switch] $AddNuGetOrgSource,

    # REV-71: on a re-run, overwrite the existing appsettings.Production.json with the newly generated one. Off by
    # default: the existing file may hold changes made after install, and the new one is written beside it instead.
    [switch] $ReplaceSettings
)

$ErrorActionPreference = 'Stop'

# --- Merge an optional answers file (explicit -Params win; passwords are never read from it) ---
if ($ConfigFile) {
    if (-not (Test-Path $ConfigFile)) { throw "Config file not found: $ConfigFile" }
    $cfg = Import-PowerShellDataFile -Path $ConfigFile
    # config key -> script variable. 'AppAccount' fills -AppPoolIdentity (one identity for DB + app pool).
    $mapping = [ordered]@{
        AppAccount            = 'AppPoolIdentity'
        SitePath              = 'SitePath'
        DataRoot              = 'DataRoot'
        EvidencePath          = 'EvidencePath'
        Hostname              = 'Hostname'
        SqlInstance           = 'SqlInstance'
        DbName                = 'DbName'
        SiteName              = 'SiteName'
        AppPoolName           = 'AppPoolName'
        CertificateThumbprint = 'CertificateThumbprint'
        AdGroupAnalysts       = 'AdGroupAnalysts'
        AdGroupCommanders     = 'AdGroupCommanders'
        AdGroupLeadership     = 'AdGroupLeadership'
        AdGroupLegal          = 'AdGroupLegal'
        AdGroupAppAdmins      = 'AdGroupAppAdmins'
        SmtpHost              = 'SmtpHost'
        MailDomain            = 'MailDomain'
        SmtpSignIn            = 'SmtpSignIn'
        SmtpUsername          = 'SmtpUsername'
        SmtpPasswordSource    = 'SmtpPasswordSource'
        SmtpPasswordSecret    = 'SmtpPasswordSecret'
        SmtpPasswordThumbprint = 'SmtpPasswordThumbprint'
        SigningKeySource      = 'SigningKeySource'
        SigningKeyThumbprint  = 'SigningKeyThumbprint'
        SigningKeySecret      = 'SigningKeySecret'
        ChainKeySource        = 'ChainKeySource'
        ChainKeySecret        = 'ChainKeySecret'
        ChainKeyThumbprint    = 'ChainKeyThumbprint'
        EvidenceEncryption    = 'EvidenceEncryption'
        EvidenceKeyThumbprint = 'EvidenceKeyThumbprint'
        RecoveryCertificates  = 'RecoveryCertificates'
    }
    foreach ($key in $mapping.Keys) {
        $var = $mapping[$key]
        # -AppPoolIdentity may have been bound via its 'AppAccount' alias; treat either as explicit.
        $boundExplicitly = $PSBoundParameters.ContainsKey($var) -or ($var -eq 'AppPoolIdentity' -and $PSBoundParameters.ContainsKey('AppAccount'))
        if (-not $boundExplicitly -and $cfg.ContainsKey($key) -and "$($cfg[$key])" -ne '') {
            Set-Variable -Name $var -Value $cfg[$key]
        }
    }
}
# Required, whichever source they came from.
$required = @{
    AppPoolIdentity = $AppPoolIdentity; SitePath = $SitePath; DataRoot = $DataRoot; Hostname = $Hostname
    SqlInstance = $SqlInstance; AdGroupAnalysts = $AdGroupAnalysts; AdGroupCommanders = $AdGroupCommanders
    AdGroupLeadership = $AdGroupLeadership; AdGroupLegal = $AdGroupLegal; AdGroupAppAdmins = $AdGroupAppAdmins
}
$missing = @($required.GetEnumerator() | Where-Object { [string]::IsNullOrWhiteSpace($_.Value) } | ForEach-Object { $_.Key })
if ($missing.Count) {
    throw "Missing required value(s): $($missing -join ', '). Pass as -Parameters or set them in -ConfigFile (see casebook.config.template.psd1)."
}

$deployDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot  = Split-Path -Parent $deployDir
$webProj   = Join-Path $repoRoot 'src\IncidentManager.Web\IncidentManager.Web.csproj'
$template  = Join-Path $deployDir 'appsettings.Production.template.json'

if (-not (Test-Path $template)) { throw "Missing expected path: $template" }
if (-not $SkipPublish -and -not (Test-Path $webProj)) { throw "Missing expected path: $webProj (use -SkipPublish to install a pre-published app)" }

function Write-Step($m) { Write-Host "==> $m" -ForegroundColor Cyan }

# --- CAP-05: the relay sign-in, checked (and its password asked for) before anything changes ---------------------
if ($SmtpSignIn -notin @('App', 'Windows', 'Password')) { throw "SmtpSignIn must be App, Windows or Password (got '$SmtpSignIn')." }
if ($SmtpPasswordSource -notin @('Protected', 'CyberArk', 'Literal')) { throw "SmtpPasswordSource must be Protected, CyberArk or Literal (got '$SmtpPasswordSource')." }
$smtpUserValue = ''; $smtpPasswordValue = ''; $smtpProtectThumbprint = ''
$smtpPlain = $null
if ($SmtpSignIn -eq 'Password') {
    if ([string]::IsNullOrWhiteSpace($SmtpUsername)) { throw "SmtpSignIn is Password but SmtpUsername is empty." }
    $smtpUserValue = $SmtpUsername.Trim()
    if ($SmtpPasswordSource -eq 'CyberArk') {
        if ($SmtpPasswordSecret -notmatch '^\s*@cyberark:') { throw "SmtpPasswordSource is CyberArk: set SmtpPasswordSecret to an @cyberark:Safe=...;Object=... reference." }
        $smtpPasswordValue = $SmtpPasswordSecret.Trim()
    } else {
        if (-not $SmtpPassword) { $SmtpPassword = Read-Host -AsSecureString "Password for the SMTP account $smtpUserValue" }
        $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($SmtpPassword)
        try { $smtpPlain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
        finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
        if ([string]::IsNullOrEmpty($smtpPlain)) { throw "The SMTP password is empty." }
        if ($SmtpPasswordSource -eq 'Protected') {
            # The certificate the site already protects its keys with, unless one is named for it.
            $smtpProtectThumbprint = ($SmtpPasswordThumbprint -replace '[^0-9A-Fa-f]', '')
            if (-not $smtpProtectThumbprint) { $smtpProtectThumbprint = ($EvidenceKeyThumbprint -replace '[^0-9A-Fa-f]', '') }
            if (-not $smtpProtectThumbprint -and $ChainKeySource -eq 'Certificate') { $smtpProtectThumbprint = ($ChainKeyThumbprint -replace '[^0-9A-Fa-f]', '') }
            if (-not $smtpProtectThumbprint -and $SigningKeySource -eq 'CertificateStore') { $smtpProtectThumbprint = ($SigningKeyThumbprint -replace '[^0-9A-Fa-f]', '') }
            if (-not $smtpProtectThumbprint) {
                throw ("SmtpPasswordSource is Protected but there's no certificate to encrypt it to. Set SmtpPasswordThumbprint " +
                       "(a certificate in LocalMachine\My), or use -SmtpSignIn App and enter the password in Administration after install.")
            }
            $keytool = Join-Path $deployDir 'keytool\casebook-keytool.exe'
            if (-not (Test-Path $keytool)) {
                throw ("$keytool isn't here (it ships in the release bundle). Run it later by hand: casebook-keytool protect-secret " +
                       "--cert $smtpProtectThumbprint, and put the value in Email:SmtpPassword; or use -SmtpSignIn App.")
            }
        } else {
            Write-Warning "The SMTP password will be written to appsettings.Production.json as plain text. Protected or App is safer."
            $smtpPasswordValue = $smtpPlain
        }
    }
}

# Preflight: the app-pool identity must resolve to a Windows SID up front - it is used for the NTFS
# ACLs, the IIS app-pool identity, and it must match the SQL login from Install-Database.ps1. Failing
# here (before publish/config) gives a clear message instead of a late IdentityNotMappedException.
try {
    [void] ([System.Security.Principal.NTAccount]::new($AppPoolIdentity)).Translate([System.Security.Principal.SecurityIdentifier])
} catch {
    throw ("The app-pool identity '$AppPoolIdentity' could not be resolved to a Windows account on this host. " +
           "For a group Managed Service Account (gMSA) include the trailing '`$' (e.g. 'AD\svc-casebook`$'). " +
           "For a normal domain account use DOMAIN\sAMAccountName and confirm the account exists and this server " +
           "is domain-joined and can reach a domain controller. It must match the SQL login from Install-Database.ps1.")
}

# Preflight (REV-70): a normal (non-gMSA) service account needs its password for the app pool. Without one the pool
# would be set to an empty password and the site would answer 503 (a re-run would also wipe a working one), so ask now,
# before anything is changed, and stop if none is given.
if (-not $AppPoolIdentity.EndsWith('$') -and -not $AppPoolCredential) {
    Write-Host "    $AppPoolIdentity is a normal service account (not a gMSA), so the app pool needs its password." -ForegroundColor Yellow
    $AppPoolCredential = Get-Credential -UserName $AppPoolIdentity -Message "Password for the CaseBook app pool account $AppPoolIdentity"
    if (-not $AppPoolCredential) {
        throw ("No password was given for '$AppPoolIdentity'. Re-run with -AppPoolCredential (Get-Credential), or use a " +
               "gMSA (an account ending in '`$'), which needs none.")
    }
}

# Preflight: the ASP.NET Core Module must be registered or IIS can't run the app - it fails with HTTP
# 500.19 (0x8007000d) because the web.config's <aspNetCore> section is unknown. The module ships with the
# .NET Hosting Bundle, NOT the SDK, so a publish-capable box can still be missing it.
# The ASP.NET Core Module, wherever this PowerShell can see it. A 32-bit PowerShell (Windows PowerShell (x86))
# has System32 redirected to SysWOW64 and $env:ProgramFiles pointed at "Program Files (x86)", so check the real
# 64-bit locations (Sysnative, ProgramW6432) and the module's registry key in both views as well.
function Test-AspNetCoreModule {
    foreach ($p in @((Join-Path $env:WINDIR 'System32\inetsrv\aspnetcorev2.dll'),
                     (Join-Path $env:WINDIR 'Sysnative\inetsrv\aspnetcorev2.dll'))) {
        if (Test-Path $p) { return $true }
    }
    foreach ($view in 'Registry64', 'Registry32') {
        try {
            $k = [Microsoft.Win32.RegistryKey]::OpenBaseKey('LocalMachine', $view).OpenSubKey('SOFTWARE\Microsoft\IIS Extensions\IIS AspNetCore Module V2')
            if ($k) { $k.Dispose(); return $true }
        } catch { }
    }
    $pf64 = if ($env:ProgramW6432) { $env:ProgramW6432 } else { $env:ProgramFiles }
    return (Test-Path (Join-Path $pf64 'IIS\Asp.Net Core Module\V2'))
}
if (-not (Test-AspNetCoreModule)) {
    throw ("The ASP.NET Core Module (aspnetcorev2.dll) is not installed, so IIS cannot host the app " +
           "(it would fail with HTTP 500.19). Install the .NET 10 Hosting Bundle from " +
           "https://dotnet.microsoft.com/download/dotnet/10.0 (ASP.NET Core Runtime -> Hosting Bundle), " +
           "run 'iisreset', then re-run this script.")
}

# --- 1. Publish (or use a pre-published folder) -------------------------------
$appDll = Join-Path $SitePath 'IncidentManager.Web.dll'
# REV-71: a re-run publishes over a live site. The in-process worker holds the DLLs, so the pool is stopped (and its
# worker gone) first; step 5 starts it again.
. (Join-Path $deployDir 'lib\CaseBookIis.ps1')
if (Test-Path $appDll) {
    Write-Step "Stopping app pool '$AppPoolName' (the site already has an install)"
    Stop-CaseBookAppPool -Name $AppPoolName
}
if ($SkipPublish) {
    Write-Step "Skipping publish; using pre-published app at $SitePath"
    if (-not (Test-Path $appDll)) {
        throw "-SkipPublish was set but $appDll is missing. Publish on a machine with internet " +
              "(dotnet publish $webProj -c $PublishConfiguration -o <folder>) and copy the output into $SitePath first."
    }
} else {
    Write-Step "Publishing CaseBook ($PublishConfiguration) to $SitePath"
    if (-not (Get-Command dotnet -ErrorAction SilentlyContinue)) {
        throw "The .NET 10 SDK ('dotnet') is required on this host to publish. Install the SDK, or publish " +
              "elsewhere, copy the output into $SitePath, and re-run with -SkipPublish."
    }

    # Preflight: no registered/enabled NuGet source => restore fails NU1100 for every package. Catch it
    # here with an exact fix instead of a slow, opaque publish failure.
    $sourcesOut = (& dotnet nuget list source 2>&1 | Out-String)
    if ($sourcesOut -notmatch '\[Enabled\]') {
        $addCmd = 'dotnet nuget add source https://api.nuget.org/v3/index.json -n nuget.org'
        if ($AddNuGetOrgSource) {
            Write-Step "No enabled NuGet source found; registering nuget.org"
            & dotnet nuget add source https://api.nuget.org/v3/index.json -n nuget.org
            if ($LASTEXITCODE -ne 0) { throw "Failed to add the nuget.org source (exit $LASTEXITCODE)." }
        } else {
            throw ("No enabled NuGet package source is registered for this user, so 'dotnet publish' will fail " +
                   "with NU1100. Register nuget.org:  $addCmd  (or re-run with -AddNuGetOrgSource), point at your " +
                   "internal feed, or publish elsewhere and re-run with -SkipPublish. Note: NuGet sources are " +
                   "per-user, so register them as the same account that runs this script.")
        }
    }

    New-Item -ItemType Directory -Force -Path $SitePath | Out-Null
    & dotnet publish $webProj -c $PublishConfiguration -o $SitePath --nologo
    if ($LASTEXITCODE -ne 0) {
        throw ("dotnet publish failed (exit $LASTEXITCODE). A NuGet restore error (NU1100) with connectivity " +
               "present usually means no package source is registered: run 'dotnet nuget list source', and if " +
               "nuget.org is missing add it with " +
               "'dotnet nuget add source https://api.nuget.org/v3/index.json -n nuget.org', then re-run. " +
               "Alternatively publish on another machine and re-run this script with -SkipPublish.")
    }
}

# --- 2. Data root (outside web root) + subfolders -----------------------------
Write-Step "Creating ACL-restricted data root at $DataRoot"
# PROD-56: evidence may live elsewhere (another volume, a UNC share); the data root keeps everything else.
$separateEvidence = -not [string]::IsNullOrWhiteSpace($EvidencePath)
if (-not $separateEvidence) { $EvidencePath = Join-Path $DataRoot 'evidence-store' }
$dataSubdirs = @('report-output','branding','report-templates','keys','seals','ops','dp-keys')
if (-not $separateEvidence) { $dataSubdirs = @('evidence-store') + $dataSubdirs }
$dataDirs = $dataSubdirs | ForEach-Object { Join-Path $DataRoot $_ }
foreach ($d in @($DataRoot) + $dataDirs) { New-Item -ItemType Directory -Force -Path $d | Out-Null }
if ($separateEvidence) {
    Write-Step "Creating the evidence store at $EvidencePath"
    try { New-Item -ItemType Directory -Force -Path $EvidencePath | Out-Null }
    catch { throw "The evidence store '$EvidencePath' couldn't be created as $([Environment]::UserDomainName)\$([Environment]::UserName): $($_.Exception.Message). Create it (and grant the rights below), then re-run." }
}

# --- 2b. AD role groups as DOMAIN\Group ---------------------------------------
# BUG-224: a bare group name maps only that group in this server's own domain (BUG-188). Groups in another domain
# (SOC groups in CORP, web server in a resource domain) would map nobody, SysAdmin included, so each is written with
# the domain it resolves to here.
. (Join-Path $deployDir 'lib\CaseBookAdGroups.ps1')
Write-Step "Resolving the AD role groups"
$AdGroupAnalysts   = ConvertTo-CaseBookGroupName 'Analysts'            $AdGroupAnalysts   -OnWebServer
$AdGroupCommanders = ConvertTo-CaseBookGroupName 'Incident Commanders' $AdGroupCommanders -OnWebServer
$AdGroupLeadership = ConvertTo-CaseBookGroupName 'Leadership'          $AdGroupLeadership -OnWebServer
$AdGroupLegal      = ConvertTo-CaseBookGroupName 'Legal/Privacy'       $AdGroupLegal      -OnWebServer
$AdGroupAppAdmins  = ConvertTo-CaseBookGroupName 'App Admins'          $AdGroupAppAdmins  -OnWebServer

# --- 2b. Recovery certificates for evidence encryption (PROD-57) ---------------
# Only the public part: a .cer holding a private key would put the offline backup on the server.
$recoveryOnServer = @()
$recoveryList = @($RecoveryCertificates | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) })
if ($recoveryList.Count) {
    $recoveryDir = Join-Path $DataRoot 'keys\recovery'
    Write-Step "Copying $($recoveryList.Count) recovery certificate(s) to $recoveryDir"
    New-Item -ItemType Directory -Force -Path $recoveryDir | Out-Null
    foreach ($src in $recoveryList) {
        if (-not (Test-Path $src)) { throw "Recovery certificate '$src' not found." }
        try { $rc = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2 -ArgumentList (Resolve-Path $src).Path }
        catch { throw "Recovery certificate '$src' couldn't be read as a public certificate (a password-protected .pfx holds the private key: give the exported .cer instead)." }
        if ($rc.HasPrivateKey) { throw "Recovery certificate '$src' contains its private key. Export the public part only (a .cer) and keep the private key offline." }
        if (-not [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPublicKey($rc)) { throw "Recovery certificate '$src' isn't RSA." }
        $dest = Join-Path $recoveryDir ("casebook-recovery-" + $rc.Thumbprint + ".cer")
        Copy-Item -Path $src -Destination $dest -Force
        $recoveryOnServer += $dest
        Write-Host "    $($rc.Thumbprint)  $($rc.Subject)  (expires $($rc.NotAfter.ToString('yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)))"
    }
}
if ($EvidenceEncryption -and -not $recoveryOnServer.Count) {
    Write-Warning ("Evidence encryption is turned on with no recovery certificate. Nothing is encrypted until a backup exists: " +
        "after install, run deploy\keytool\casebook-keytool split --site $SitePath (OPERATIONS.md section 2).")
}

# --- 3. appsettings.Production.json from template -----------------------------
# CAP-05: a Protected SMTP password becomes its @protected: value here; the plain text goes to the keytool's stdin only.
if ($smtpProtectThumbprint) {
    Write-Step "Encrypting the SMTP password to certificate $smtpProtectThumbprint"
    # CAP-05 review: Windows PowerShell pipes to a native exe in $OutputEncoding, US-ASCII by default, which turns a
    # non-ASCII password into '?'. Pipe it as UTF-8 (no BOM; the keytool reads redirected stdin as UTF-8), then restore.
